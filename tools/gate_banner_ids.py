"""Writes the gate banner id lists from the game's master database.

    python tools/gate_banner_ids.py [--master PATH] [--out docs/gate_banner]

- `races.csv`: every race instance (instance id, race id, name, mode, grade,
  course, distance, ground, runners, gate size).
- `RACES.md`: the courses, then the Room Match and Champions Meeting races
  per course (the races spectators watch), with the file names to use.

`master.mdb` is plain SQLite (standard library only). Default location:
%LOCALAPPDATA%Low\\Cygames\\Umamusume\\master\\master.mdb. Run it again after a
game update to pick up new races.
"""

import argparse
import csv
import os
import shutil
import sqlite3
import sys
import tempfile
from collections import defaultdict

# master text_data categories
RACE_NAME = 32  # by race id
INSTANCE_NAME = 28  # by race instance id
COURSE_NAME = 35  # by race_track_id

# race."group" -> mode. Named from their race names; the others stay "group N".
MODES = {
    1: "Career",
    3: "URA Finale",
    5: "Scout",
    6: "Practice",
    7: "Career",
    9: "Team Trials",
    10: "Showdown",
    11: "Champions Meeting",
    12: "Room Match",
    13: "Carnival",
}
GRADES = {100: "G1", 200: "G2", 300: "G3", 400: "OP"}
GROUNDS = {1: "Turf", 2: "Dirt"}
# JRA courses use one gate set (race.start_gate 0): 18 stalls, or 9 for small fields.
JRA_GATE = 0
HALF_GATE_MAX_RUNNERS = 9
SPECTATOR_MODES = ("Room Match", "Champions Meeting")


def default_master():
    local = os.environ.get("LOCALAPPDATA", "")
    return os.path.join(os.path.dirname(local), "LocalLow", "Cygames", "Umamusume", "master", "master.mdb")


def gate_size(start_gate, runners):
    if start_gate != JRA_GATE:
        return "own"
    return "9" if runners <= HALF_GATE_MAX_RUNNERS else "18"


def load(master):
    # Work on a copy: the game may hold the file open.
    tmp = os.path.join(tempfile.mkdtemp(), "master.mdb")
    shutil.copyfile(master, tmp)
    db = sqlite3.connect(tmp)
    text = defaultdict(dict)
    for cat, idx, t in db.execute(
        "select category, \"index\", text from text_data where category in (?, ?, ?)",
        (RACE_NAME, INSTANCE_NAME, COURSE_NAME),
    ):
        text[cat][idx] = t
    rows = db.execute(
        """select ri.id, r.id, r."group", r.grade, r.entry_num, r.start_gate,
                  rc.race_track_id, rc.distance, rc.ground
           from race_instance ri
           join race r on r.id = ri.race_id
           join race_course_set rc on rc.id = r.course_set
           order by rc.race_track_id, r.id, ri.id"""
    ).fetchall()
    races = []
    for inst, race, group, grade, runners, start_gate, course, distance, ground in rows:
        races.append(
            {
                "instance_id": inst,
                "race_id": race,
                "name": text[RACE_NAME].get(race) or text[INSTANCE_NAME].get(inst, ""),
                "mode": MODES.get(group, f"group {group}"),
                "grade": GRADES.get(grade, ""),
                "course_id": course,
                "course": text[COURSE_NAME].get(course, str(course)),
                "distance": distance,
                "ground": GROUNDS.get(ground, str(ground)),
                "runners": runners,
                "gate": gate_size(start_gate, runners),
            }
        )
    db.close()
    return races


def write_csv(races, path):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(races[0].keys()))
        w.writeheader()
        w.writerows(races)


def write_md(races, path):
    courses = {}
    jra = set()
    for r in races:
        courses.setdefault(r["course_id"], r["course"])
        if r["gate"] != "own":
            jra.add(r["course_id"])
    out = [
        "# Gate banner ids",
        "",
        "Generated by `tools/gate_banner_ids.py` from the game's master data: run it again after a",
        "game update. Every race instance is in [races.csv](races.csv); how to use the ids:",
        "[README.md](README.md).",
        "",
        "## Courses",
        "",
        "| Course id | Course | Gate | File names |",
        "|---|---|---|---|",
    ]
    for cid, name in sorted(courses.items()):
        if cid in jra:
            out.append(f"| {cid} | {name} | JRA (18 / 9) | `course_{cid}_18.png`, `course_{cid}_9.png`, `course_{cid}.png` |")
        else:
            out.append(f"| {cid} | {name} | own (size: see the menu) | `course_{cid}.png` (untested) |")
    for mode in SPECTATOR_MODES:
        out += ["", f"## {mode}", ""]
        by_course = defaultdict(dict)
        for r in races:
            if r["mode"] == mode:
                by_course[r["course_id"]].setdefault(r["race_id"], r)
        for cid in sorted(by_course):
            out += [f"### {courses[cid]} ({cid})", "", "| Race id | Race | Distance | Runners | Gate | File name |", "|---|---|---|---|---|---|"]
            for rid, r in sorted(by_course[cid].items()):
                size = r["gate"]
                file = f"`{rid}_{size}.png`" if size != "own" else f"`{rid}.png`"
                out.append(
                    f"| {rid} | {r['name']} | {r['ground']} {r['distance']}m | {r['runners']} | {size} | {file} |"
                )
            out.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out).rstrip() + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--master", default=default_master(), help="path to master.mdb")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "docs", "gate_banner"))
    args = ap.parse_args()
    if not os.path.isfile(args.master):
        sys.exit(f"master.mdb not found at {args.master}; pass --master")
    races = load(args.master)
    os.makedirs(args.out, exist_ok=True)
    write_csv(races, os.path.join(args.out, "races.csv"))
    write_md(races, os.path.join(args.out, "RACES.md"))
    print(f"{len(races)} race instances -> {os.path.normpath(args.out)}")


if __name__ == "__main__":
    main()
